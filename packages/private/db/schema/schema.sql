-- One row per prior version of a `thread_message_content.content`, oldest edits first by `id` -- same
-- "archive the old value before overwriting" shape as `snippet_updates` below, written by
-- `lib/threads.ts`'s `updateRecordedMessageContent` (Phase 3, #261) instead of the blind overwrite it used
-- to do. No `edited_by` column -- unlike a snippet edit (staff-driven), a recorded message's editor is
-- always that message's own author, already known via `thread_messages.user_id`/`staff_id`.
CREATE TABLE thread_message_content_edits (
  id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  thread_message_id  INTEGER NOT NULL REFERENCES thread_message_content (thread_message_id) ON DELETE CASCADE,
  edited_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  old_content        TEXT NOT NULL
);

CREATE INDEX thread_message_content_edits_thread_message_id_idx ON thread_message_content_edits (thread_message_id);

CREATE TABLE scheduled_thread_closes (
  thread_id       INTEGER PRIMARY KEY REFERENCES threads (id) ON DELETE CASCADE,
  scheduled_by_id TEXT NOT NULL,
  silent          BOOLEAN NOT NULL DEFAULT false,
  -- Whether the farewell message this schedule eventually posts should be anonymous ("{guildName}
  -- Team") instead of attributed to scheduled_by_id -- mirrors /close now's anon option (and
  -- /reply's), see services/modmail-bot's lib/threadClose.ts. Attributed is the default, matching
  -- staff replies.
  anon            BOOLEAN NOT NULL DEFAULT false,
  close_at        TIMESTAMPTZ NOT NULL
);

-- A closed ticket's private thread is locked immediately (services/modmail-bot's `lib/threadClose.ts`)
-- but not deleted outright -- a row here is what a periodic sweep (`lib/threadNukeSweep.ts`) polls to
-- actually delete it once `guild_settings.nuke_delay_minutes` has passed. Only written when that column
-- is non-NULL (deletion is opt-in); a guild that never opts in simply never gets a row. Cascades with
-- `threads` since there's nothing left to nuke if the ticket row itself is gone.
CREATE TABLE scheduled_thread_nukes (
  thread_id INTEGER PRIMARY KEY REFERENCES threads (id) ON DELETE CASCADE,
  nuke_at   TIMESTAMPTZ NOT NULL
);

